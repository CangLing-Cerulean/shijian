package schedule.app

import androidx.activity.compose.BackHandler
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.unit.dp
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import schedule.android.MaterialStore
import schedule.android.SavedMaterial
import schedule.study.*

@Composable fun LessonMaterialsScreen(model: AppModel, itemId: String, onBack: () -> Unit, onTranscript: () -> Unit) {
    val item = model.state?.items?.find { it.id == itemId }
    if (item == null) { Column { PageTitle("资料", onBack); Text("课程安排已删除") }; return }
    var picking by remember(itemId) { mutableStateOf(false) }
    var generated by remember(itemId) { mutableStateOf(false) }
    var linked by remember(itemId) { mutableStateOf<List<LessonMaterial>>(emptyList()) }
    var openedSummary by remember(itemId) { mutableStateOf<SavedSummary?>(null) }
    var openedPdf by remember(itemId) { mutableStateOf<SavedMaterial?>(null) }
    val context = LocalContext.current
    val files = remember(context) { MaterialStore(context) }
    LaunchedEffect(itemId, picking) {
        try { linked = withContext(Dispatchers.IO) { model.runtime.library.read().lessonMaterials.filter { it.itemId == itemId } }; model.reloadLibrary() }
        catch (e: kotlinx.coroutines.CancellationException) { throw e }
        catch (e: Exception) { model.error = e.message }
    }
    DisposableEffect(itemId) { onDispose { model.studyContext = null } }
    LaunchedEffect(itemId, picking, openedPdf, openedSummary, generated) {
        if (!picking && openedPdf == null) model.studyContext = "当堂资料：${item.title}，itemId=$itemId，上课时间=${dateTimeText(item.startAt)}，当前分类=${if (generated) "生成总结" else "原始资料"}"
    }
    if (picking) { CourseScreen(model, onBack = { picking = false }, itemId = itemId); BackHandler { picking = false }; return }
    openedSummary?.let { summary ->
        SummaryReader(summary, onBack = { openedSummary = null }, onDelete = { model.deleteSummaries(setOf(summary.id)); openedSummary = null })
        return
    }
    openedPdf?.let { saved ->
        BackHandler { openedPdf = null }
        PdfScreen(files.file(saved), saved.originalName, onBack = { openedPdf = null }, onError = { model.error = it }, onPage = { page -> model.studyContext = "当堂资料itemId=$itemId，学在浙大courseId=${saved.courseId}，uploadId=${saved.material.uploadId}，PDF第${page}页" })
        return
    }
    Column(Modifier.fillMaxSize().padding(horizontal = 22.dp)) {
        PageTitle("当堂资料", onBack)
        Text(item.title, style = MaterialTheme.typography.titleMedium)
        Text(dateTimeText(item.startAt), style = MaterialTheme.typography.labelMedium, color = MaterialTheme.colorScheme.onSurfaceVariant)
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            FilterChip(!generated, { generated = false }, label = { Text("原始资料") })
            FilterChip(generated, { generated = true; model.launchWork { model.reloadLibrary() } }, label = { Text("生成总结") })
        }
        if (generated) {
            SummaryList(model, model.summaries.filter { it.courseName == item.title && it.lessonStart == item.startAt }, Modifier.weight(1f), onOpen = { openedSummary = it })
        } else LazyColumn(Modifier.weight(1f), contentPadding = PaddingValues(bottom = 100.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
            item {
                OutlinedCard(onClick = onTranscript, modifier = Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp)) { Text("课堂转录", style = MaterialTheme.typography.titleMedium); Text("智云课堂", style = MaterialTheme.typography.labelMedium) }
                }
            }
            item { TextButton(onClick = { picking = true; model.loadCourses() }) { Text("从学在浙大选择课件") } }
            items(linked, key = { it.id }) { source ->
                OutlinedCard(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(16.dp)) {
                        Text(source.material.name, style = MaterialTheme.typography.titleMedium)
                        Text("学在浙大 · ${source.material.activityTitle}", style = MaterialTheme.typography.labelSmall)
                        Row {
                            TextButton(onClick = { model.launchWork {
                                val saved = withContext(Dispatchers.IO) {
                                    files.list().find { it.courseId == source.courseId && it.material == source.material } ?: run {
                                        require(model.runtime.listCourses().any { it.courseId == source.courseId }) { "仅下载本学期课件，已下载文件可离线阅读" }
                                        files.save(source.courseId, source.courseName, source.material, model.runtime.downloadCourseMaterialByUser(source.material))
                                    }
                                }
                                if (source.material.name.endsWith(".pdf", true)) openedPdf = saved else model.notice = "已下载，可在资料的已下载中导出"
                            } }, enabled = !model.working) { Text(if (source.material.name.endsWith(".pdf", true)) "阅读" else "下载") }
                            TextButton(onClick = { model.launchWork {
                                withContext(Dispatchers.IO) { model.runtime.library.unlinkMaterial(source.id) }
                                linked = linked.filterNot { it.id == source.id }
                            } }, enabled = !model.working) { Text("移出当堂") }
                        }
                    }
                }
            }
        }
    }
}
